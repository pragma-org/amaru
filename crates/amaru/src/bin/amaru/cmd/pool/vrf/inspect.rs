use std::{fs, path::PathBuf};

use amaru::lifecycle::{Runnable, RuntimeKind};
use amaru_kernel::Hasher;
use amaru_ouroboros::vrf::PublicKey;
use anyhow::Context;

/// Print the Blake2b-256 hash of a VRF verification key.
#[derive(Debug, clap::Args)]
pub struct InspectArgs {
    /// Raw 32-byte VRF verification key generated by `amaru pool vrf create`.
    #[arg(long, value_name = amaru::value_names::FILEPATH)]
    verification_key: PathBuf,
}

impl InspectArgs {
    pub fn into_runnable(self) -> Runnable {
        Runnable::exit_on_signal(RuntimeKind::Simple, move || async move { self.run() })
    }

    #[expect(clippy::print_stdout)]
    pub fn run(self) -> anyhow::Result<()> {
        let bytes = fs::read(&self.verification_key)
            .with_context(|| format!("failed to load VRF verification key: {}", self.verification_key.display()))?;

        let key =
            PublicKey::try_from(bytes.as_slice()).context("VRF verification key must contain exactly 32 raw bytes")?;

        println!("{}", Hasher::<{ 8 * PublicKey::HASH_SIZE }>::hash(key.as_ref()));

        Ok(())
    }
}
